/**
 * Builds the hark app icon from a few parameters.
 *
 * Design primitives borrowed from kip so the two apps read as one family:
 *   - macOS body: 824x824 superellipse (n=5) on a 1024 canvas, 100 px safe margin
 *   - one monochrome glyph on obsidian #141416, nothing else on the plate
 *   - proportions from phi, a slight clockwise tilt for the family look
 *   - metal facet variant for >= 64 px, flat variant below that
 *
 * Glyph: three level bars, phi-stepped — you ask, the answer arrives as sound.
 * Emits:
 *   appicon.svg       3 bars, metal facets (icns / ico source)
 *   appicon-flat.svg  3 bars, flat (32 px)
 *   favicon.svg       2 bars, flat (16 px; three bars turn to mush there)
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// ---- Tunables -------------------------------------------------------------
const C = 512; // canvas centre
const PLATE_A = 412; // superellipse half-size => 100 px safe margin
const PLATE_N = 5;
const PLATE_FILL = "#141416";
const PAPER = "#FAF9F6";
const PHI = (1 + Math.sqrt(5)) / 2;
const TILT = -8; // counter-clockwise, degrees (kip tilts its aperture the other way)
const BAR_H = [0.62, 1, 0.78]; // relative heights; the middle one anchors the mark
const BAR_W = 0.2; // width as a fraction of the tallest bar
const GAP = 0.42; // gap as a fraction of the bar width
const OPTICAL_W = 500; // glyph width after fitting, keeps the plate breathing
const OPTICAL_NUDGE = 0.0;
// ---------------------------------------------------------------------------

const iconDir = dirname(fileURLToPath(import.meta.url));
const buildDir = join(iconDir, "..");
const publicDir = join(buildDir, "..", "frontend", "public");
const rad = (TILT * Math.PI) / 180;
const fmt = (n) => n.toFixed(2);
const rotate = ([x, y]) => [x * Math.cos(rad) - y * Math.sin(rad), x * Math.sin(rad) + y * Math.cos(rad)];

function squircle(steps) {
  const pts = [];
  for (let i = 0; i < steps; i++) {
    const t = (i / steps) * 2 * Math.PI;
    const ct = Math.cos(t);
    const st = Math.sin(t);
    const x = C + PLATE_A * Math.sign(ct) * Math.abs(ct) ** (2 / PLATE_N);
    const y = C + PLATE_A * Math.sign(st) * Math.abs(st) ** (2 / PLATE_N);
    pts.push(`${x.toFixed(1)} ${y.toFixed(1)}`);
  }
  return `M${pts.join("L")}Z`;
}

/** Rects in glyph space: bars centred on the origin, phi-stepped heights. */
function barRects(heights) {
  const h = 1;
  const w = h * BAR_W;
  const gap = w * GAP;
  const total = heights.length * w + (heights.length - 1) * gap;
  return heights.map((fraction, i) => {
    const x = -total / 2 + i * (w + gap);
    const half = (h * fraction) / 2;
    return { x, y: -half, w, h: half * 2, r: w * 0.18 };
  });
}

function glyph(heights, paintOf) {
  const rects = barRects(heights);
  const corners = rects.flatMap((r) =>
    [
      [r.x, r.y],
      [r.x + r.w, r.y],
      [r.x + r.w, r.y + r.h],
      [r.x, r.y + r.h],
    ].map(rotate),
  );
  const xs = corners.map((p) => p[0]);
  const ys = corners.map((p) => p[1]);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const minY = Math.min(...ys);
  const maxY = Math.max(...ys);
  const scale = OPTICAL_W / (maxX - minX);
  const cx = (minX + maxX) / 2 - (maxX - minX) * OPTICAL_NUDGE;
  const cy = (minY + maxY) / 2;

  return rects
    .map((r, i) => {
      const [ox, oy] = rotate([r.x + r.w / 2, r.y + r.h / 2]);
      const px = C + (ox - cx) * scale;
      const py = C + (oy - cy) * scale;
      const w = r.w * scale;
      const h = r.h * scale;
      return (
        `  <rect x="${fmt(-w / 2)}" y="${fmt(-h / 2)}" width="${fmt(w)}" height="${fmt(h)}" ` +
        `rx="${fmt(Math.min(w, h) * 0.3)}" transform="translate(${fmt(px)} ${fmt(py)}) rotate(${TILT})" fill="${paintOf(i)}"/>`
      );
    })
    .join("\n");
}

const metalStops = [
  ["#FFFFFF", "#C9C5BB"],
  ["#FFFFFF", "#EFEDE6"],
  ["#F3F1EB", "#908C83"],
];

const defs = `  <defs>
${metalStops
  .map(
    ([from, to], i) =>
      `    <linearGradient id="bar-${i}" x1="0.15" y1="0" x2="0.85" y2="1"><stop offset="0" stop-color="${from}"/><stop offset="1" stop-color="${to}"/></linearGradient>`,
  )
  .join("\n")}
    <filter id="lift" x="-25%" y="-25%" width="150%" height="160%">
      <feDropShadow dx="0" dy="16" stdDeviation="20" flood-color="#000" flood-opacity="0.6"/>
    </filter>
  </defs>
`;

const svg = (body) => `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by build/icon/generate.mjs; edit the script, not this file. -->
  <path d="${squircle(720)}" fill="${PLATE_FILL}"/>
${body}
</svg>
`;

const metal = svg(`${defs}  <g filter="url(#lift)">
${glyph(BAR_H, (i) => `url(#bar-${i})`)}
  </g>`);
const flat32 = svg(glyph(BAR_H, () => PAPER, true));
const favicon = svg(glyph([0.62, 1], () => PAPER, true));

writeFileSync(join(buildDir, "appicon.svg"), metal);
writeFileSync(join(iconDir, "appicon-flat.svg"), flat32);
writeFileSync(join(publicDir, "favicon.svg"), favicon);
console.log("wrote build/appicon.svg, build/icon/appicon-flat.svg, frontend/public/favicon.svg");
